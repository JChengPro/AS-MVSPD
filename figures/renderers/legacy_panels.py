def read_csv(name: str) -> pd.DataFrame:
    path = SOURCE / name
    if not path.exists():
        raise FileNotFoundError(f"Missing figure source data: {path}")
    frame = pd.read_csv(path)
    numeric = frame.select_dtypes(include=[np.number])
    if np.isinf(numeric.to_numpy()).any():
        raise ValueError(f"Infinite values in {path}")
    return frame


def clean_axis(ax: plt.Axes, grid: str | None = None) -> None:
    if grid:
        ax.grid(True, axis=grid, color=NEUTRAL["grid"], linewidth=0.45, zorder=0)
    ax.tick_params(length=2.2, width=0.55, pad=1.5)
    ax.set_axisbelow(True)


def apply_dense_main_style() -> None:
    """Increase text sizes for dense main figures before Word downscaling."""

    fonts = STYLE["dense_main_fonts"]
    mpl.rcParams.update(
        {
            "font.size": fonts["body_pt"],
            "axes.labelsize": fonts["axis_label_pt"],
            "axes.titlesize": fonts["axis_label_pt"],
            "xtick.labelsize": fonts["tick_pt"],
            "ytick.labelsize": fonts["tick_pt"],
            "legend.fontsize": fonts["legend_pt"],
        }
    )


def alpha_reference(ax: plt.Axes, orientation: str = "horizontal") -> None:
    if orientation == "horizontal":
        ax.axhline(ALPHA, color=NEUTRAL["mid"], linestyle=(0, (3, 2)), linewidth=0.7)
    else:
        ax.axvline(-np.log10(ALPHA), color=NEUTRAL["mid"], linestyle=(0, (3, 2)), linewidth=0.7)


def neglog_alpha_reference(ax: plt.Axes) -> None:
    """Draw the P=0.05 threshold when P is plotted on a -log10 scale."""
    ax.axhline(-np.log10(ALPHA), color=NEUTRAL["mid"], linestyle=(0, (3, 2)), linewidth=0.7)


def method_legend(ax: plt.Axes, methods: list[str], ncol: int = 2, **kwargs) -> None:
    handles = [
        Line2D(
            [0], [0], color=METHOD_COLORS[m], marker=METHOD_MARKERS[m],
            markerfacecolor="white", markeredgewidth=0.8, label=m,
        )
        for m in methods
    ]
    ax.legend(handles=handles, ncol=ncol, **kwargs)


def point_ci_panel(
    ax: plt.Axes,
    data: pd.DataFrame,
    scenario: str,
    methods: list[str] = METHOD_ORDER,
    ylabel: str = "Rejection probability",
    show_alpha: bool = True,
) -> None:
    part = data.loc[data["scenario"].fillna("null").eq(scenario)].copy()
    xvalues = [8, 12, 20]
    offsets = np.linspace(-0.22, 0.22, len(methods))
    for offset, method in zip(offsets, methods):
        m = part.loc[part["method"].eq(method)].set_index("n_subjects").reindex(xvalues)
        x = np.arange(len(xvalues)) + offset
        y = m["rate"].to_numpy(float)
        lo = m["ci_low"].to_numpy(float)
        hi = m["ci_high"].to_numpy(float)
        ax.errorbar(
            x,
            y,
            yerr=np.vstack([np.maximum(0.0, y - lo), np.maximum(0.0, hi - y)]),
            color=METHOD_COLORS[method],
            marker=METHOD_MARKERS[method],
            markerfacecolor="white",
            markeredgewidth=0.8,
            linewidth=0.8,
            capsize=1.7,
            zorder=3,
        )
    ax.set_xticks(np.arange(len(xvalues)), [str(v) for v in xvalues])
    ax.set_xlabel("Paired subjects, n")
    ax.set_ylabel(ylabel)
    ax.set_ylim(-0.015, 1.04 if scenario.startswith("stable") else 0.13)
    if show_alpha:
        alpha_reference(ax)
    clean_axis(ax, "y")


def draw_heatmap(
    ax: plt.Axes,
    matrix: np.ndarray,
    row_labels: list[str],
    col_labels: list[str],
    vlim: float | None = None,
    colorbar_label: str = "SD-scaled paired change",
    show_colorbar: bool = True,
):
    if vlim is None:
        vlim = float(np.nanpercentile(np.abs(matrix), 97.5))
    vlim = max(vlim, 1e-8)
    image = ax.imshow(matrix, aspect="auto", cmap="RdBu_r", vmin=-vlim, vmax=vlim)
    ax.set_xticks(np.arange(len(col_labels)), col_labels, rotation=55, ha="right")
    ax.set_yticks(np.arange(len(row_labels)), row_labels)
    ax.tick_params(length=0)
    for spine in ax.spines.values():
        spine.set_visible(False)
    cbar = None
    if show_colorbar:
        cbar = ax.figure.colorbar(image, ax=ax, fraction=0.035, pad=0.02)
        cbar.set_label(colorbar_label, fontsize=5.0, labelpad=1.5)
        cbar.outline.set_linewidth(0.5)
        cbar.ax.tick_params(length=2, width=0.5)
    return cbar





